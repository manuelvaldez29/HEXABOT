    private void formMouseWheelMoved(java.awt.event.MouseWheelEvent evt) {//GEN-FIRST:event_formMouseWheelMoved

        double l_factor = (evt.getWheelRotation() < 0) ? 1.2 : 0.8;
        setScale(getScale() * l_factor);

        repaint();

    }//GEN-LAST:event_formMouseWheelMoved

    private void formMouseDragged(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_formMouseDragged

        int l_deltaX = evt.getX() - m_startDrag.x;
        int l_deltaY = evt.getY() - m_startDrag.y;
        System.out.format("delta %d,%d\n", l_deltaX, l_deltaY);
        m_origin.move(m_origin.x + l_deltaX, m_origin.y + l_deltaY);
        m_startDrag = evt.getPoint();
        repaint();

    }//GEN-LAST:event_formMouseDragged

