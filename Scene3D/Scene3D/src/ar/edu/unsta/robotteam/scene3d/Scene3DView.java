    @Override
    public void paint(Graphics p_g) {
        super.paint(p_g);

        Graphics2D l_gr = (Graphics2D) p_g;

        l_gr.setRenderingHint(RenderingHints.KEY_ANTIALIASING,
                (m_aliasing) ? RenderingHints.VALUE_ANTIALIAS_ON
                        : RenderingHints.VALUE_ANTIALIAS_OFF);

        List<Line3DSegment> l_list = getModel().getSegments();
        for (Line3DSegment l_segment : l_list) {
            if (l_segment.getColor() != null) {
                l_gr.setColor(l_segment.getColor());
            } // end if

            if (l_segment.getWidth() != -1) {
                l_gr.setStroke(new BasicStroke(l_segment.getWidth()));
            } // end if

            Point3D l_pointA = getModel().getPoint(l_segment.getIdPointA());
            Point3D l_pointB = getModel().getPoint(l_segment.getIdPointB());

            Point l_a = m_projector.project(l_pointA);
            Point l_b = m_projector.project(l_pointB);

            l_gr.drawLine(l_a.x, l_a.y, l_b.x, l_b.y);

        } // end for 

    }

