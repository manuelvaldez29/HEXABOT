    private void doSendSafeThread(int p_arduino) throws Exception {
        String l_toSend = null;
        ClientServerPort l_port = null;
        switch (p_arduino) {
            case 1: {
                l_toSend = ui_txtSendCommand1.getText();
                l_port = m_arduino1;
            }
            break;
            case 2: {
                l_toSend = ui_txtSendCommand2.getText();
                l_port = m_arduino2;
            }
            break;
            case 3: {
                l_toSend = ui_txtSendCommand3.getText();
                l_port = m_arduino3;
            }
            break;
        }
        if (l_toSend == null) {
            return;
        } // end if

        String l_args = null;
        if (l_toSend.length() > 1) {
            l_args = l_toSend.substring(1);
            l_toSend = l_toSend.substring(0, 1);
        } // end if

        if (l_port != null) {
            l_port.sendCommandWaitResponse(l_toSend, l_args);
        } // end if
    }

