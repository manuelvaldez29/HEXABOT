    public void trace(String p_msg) {
        String l_txt = ui_txtTrace.getText();
        l_txt = l_txt + "\n" + p_msg;
        if (l_txt.length() > 1000) {
            l_txt = l_txt.substring(l_txt.length() - 1000);
        } // end if
        ui_txtTrace.setText(l_txt);
        ui_txtTrace.setCaretPosition(l_txt.length());
    }

