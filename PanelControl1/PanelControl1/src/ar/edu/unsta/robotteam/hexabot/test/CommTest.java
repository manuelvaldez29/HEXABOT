    private void initArduino(ClientServerPort p_arduino, String p_motors) throws
            Exception {
        if (p_arduino == null) {
            return;
        } // end if

        trace("Initizalizing Arduino...");
        for (int l_motor = 1; l_motor <= 6; l_motor++) {
            trace("Initializing motor " + l_motor);
            if (p_motors.contains(String.valueOf(l_motor))) {
                p_arduino.sendCommandWaitResponse("I", l_motor);
            } // end if
        } // end for
    }

